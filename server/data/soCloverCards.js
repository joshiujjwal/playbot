// Utility function to get a random card
export function getRandomCard() {
  return CARDS[Math.floor(Math.random() * CARDS.length)];
}

// Utility function to get N unique random cards
export function getRandomCards(count) {
  const shuffled = [...CARDS].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}

// Utility function to get rotated keywords
export function getRotatedKeywords(card, rotation) {
  const steps = rotation / 90;
  const kw = card.keywords;
  return {
    top: kw[(0 - steps + 4) % 4],
    right: kw[(1 - steps + 4) % 4],
    bottom: kw[(2 - steps + 4) % 4],
    left: kw[(3 - steps + 4) % 4]
  };
}
